namespace TrainManager.Trains
{
    /// <summary>Поломка поезда (отдельно от состояния движения).</summary>
    public enum BreakdownState
    {
        None,   // исправен
        Light,  // лёгкая поломка: ехать можно, но может сломаться в пути (нужна будет буксировка)
        Broken  // сломан: не едет, пока не починят
    }

    /// <summary>
    /// Состояние поезда.
    /// </summary>
    public enum TrainState
    {
        Idle,       // стоит на станции, готов к отправлению
        Moving,     // в пути
        Arrived,    // только что прибыл (тоже можно отправлять дальше)
        OutOfFuel,  // стоит на станции, топлива не хватает даже на толчок
        Stranded    // сломался в пути и стоит на линии — нужна буксировка
    }
}
